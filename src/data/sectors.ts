export interface SectorData {
  id: SectorId;
  code: string;
  orderLabel: string;
  domainLabel: string;
  title: string;
  shortTitle: string;
  creativeName: string;
  planetFlavor: string;
  desc: string;
  slides: SectorSlide[];
  warmup: WarmupConfig;
  subLessons: SubLesson[];
  keyPoints: KeyPointCard[];
  coolFactTitle: string;
  coolFactBody: string;
  fairyHints: string[];
  quizzes: QuizQuestion[];
}

export function getSectorStarStats(sector: SectorData, progress: SectorProgress) {
  const subDone = sector.subLessons.filter((sub) => progress.subLevels?.[sub.id]?.completed).length;
  const total = 3 + sector.subLessons.length; // slides + warmup + subLessons + lab
  const earned =
    (progress.slides ? 1 : 0) +
    (progress.warmup ? 1 : 0) +
    subDone +
    (progress.lab ? 1 : 0);
  return {
    earned,
    total,
    subDone,
    subTotal: sector.subLessons.length,
    allDone: earned === total,
  };
}

export function getTotalSystemStars(sectors: SectorData[]): number {
  return sectors.reduce((acc, s) => acc + 3 + s.subLessons.length, 0);
}

